"""THE DISTRESS BYPASS — Constitution Art. IV §4–5. Read before editing.

Runs on EVERY final transcript, before and independent of any LLM. Pure local
keyword/intent matching (see :mod:`meemoo.voice.phrases`): no network, no API
key, no model download. On a hit it publishes ``utterance.distress`` on the
bus — Guardian (Phase 5) subscribes and escalates deterministically — and the
pipeline speaks a fixed acknowledgment template. The LLM is never in this path.

Tuned recall-over-precision: "I don't need help" still fires — a false alarm
is a cheap question, a miss is the catastrophe. The wake word ("Hey Meemoo")
was chosen to never collide with "help" (Constitution preamble); keep it that
way if phrases change.

The always-on STOP detector lives here too (research 02 §D.3): barge-in must
not depend on echo cancellation, so "stop" is handled by the same always-on
local matcher rather than the conversation loop.
"""

from __future__ import annotations

import logging

from meemoo.core import topics
from meemoo.core.bus import EventBus
from meemoo.core.logging import escalation_extra
from meemoo.voice.phrases import PhraseMatch, PhraseMatcher

logger = logging.getLogger(__name__)

# Fuzzy variants are generated by the matcher (edit distance 1 on tokens ≥ 4
# chars) — list canonical forms only. Short tokens ("me", "911") match exactly.
DISTRESS_PHRASES: tuple[str, ...] = (
    "help me",
    "i need help",
    "need help",
    "call someone",
    "call for help",
    "get help",
    "send help",
    "somebody help",
    "someone help",
    "emergency",
    "call 911",
    "call nine one one",
    "i've fallen",
    "i have fallen",
    "i fell",
    "i can't get up",
    "i cant get up",
    "can't get up",
    "help",  # bare shout — recall over precision (Art. IV §5)
)

STOP_PHRASES: tuple[str, ...] = (
    "stop",
    "stop talking",
    "stop it",
    "be quiet",
    "quiet",
    "hush",
    "shush",
    "shut up",
    "that's enough",
    "enough",
)

# Deterministic spoken acknowledgment — a template, never generated.
DISTRESS_ACK = (
    "I hear you. I'm getting help right now — I'm contacting your people. "
    "Stay where you are, I'm staying with you."
)


class DistressDetector:
    """Local distress-phrase detector. Constructing it touches nothing external."""

    def __init__(self) -> None:
        self._matcher = PhraseMatcher(DISTRESS_PHRASES)

    def check(self, text: str) -> PhraseMatch | None:
        """Return the matched distress phrase, or ``None``."""
        return self._matcher.match(text)


class StopDetector:
    """Always-on 'stop' detector — active while Meemoo is speaking."""

    def __init__(self) -> None:
        self._matcher = PhraseMatcher(STOP_PHRASES)

    def check(self, text: str) -> PhraseMatch | None:
        return self._matcher.match(text)


async def publish_distress(
    bus: EventBus,
    match: PhraseMatch,
    *,
    transcript: str,
    device_id: int | None = None,
    conversation_id: int | None = None,
) -> None:
    """Publish ``utterance.distress`` — Guardian's direct trigger.

    Logged with escalation version stamps (which thresholds/prompts were in
    force) per Constitution Art. II §6.
    """
    payload: dict[str, object] = {
        "phrase": match.phrase,
        "matched_text": match.matched_text,
        "transcript": transcript,
        "device_id": device_id,
        "conversation_id": conversation_id,
        "source": "voice.distress",
    }
    logger.warning(
        "DISTRESS phrase detected — bypassing brain, firing Guardian",
        extra=escalation_extra(**payload),
    )
    await bus.publish(topics.DISTRESS_HEARD, payload)
